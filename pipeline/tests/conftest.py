"""Shared test fixtures: a whole synthetic site run once, end to end, in a temporary folder."""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import pytest
import yaml

from pipeline.config import load_site
from pipeline.paths import Layout
from pipeline.stages import run_site
from pipeline.tests.synth import BrightSpot, SynthGrid, synthetic_name, write_synthetic_gcov

SITE_ID = "synthetic-test"
DATES = ["2026-06-07", "2026-06-19", "2026-07-01"]
LEVELS_DB = [-15.0, -12.0, -9.0]  # rising on purpose, so band order is visible in the stack


@dataclass
class SyntheticRun:
    layout: Layout
    grid: SynthGrid
    spot: BrightSpot
    exit_code: int

    @property
    def data(self) -> Path:
        return self.layout.site_data(SITE_ID)


def make_synthetic_site(root: Path, convention: str = "subswath", *, files: dict[str, dict] | None = None,
                        site: dict | None = None, common: dict | None = None, dates: list[str] = DATES,
                        levels: list[float] | None = None) -> Layout:
    """Write SYNTHETIC granules (one per date of `dates`, three by default) plus a site file and granule list
    that point at them.

    `common` holds extra arguments of write_synthetic_gcov for every file (for example synth.REAL_FORMAT
    without its convention); `files` maps a date to extra arguments for that date's file only (a scene, a
    hole, another grid or stack); `site` overrides fields of the site file. `levels` are the speckle levels
    in dB of the dates (default LEVELS_DB for the default dates, -15 dB otherwise).
    """
    if levels is None:
        levels = LEVELS_DB if dates == DATES else [-15.0] * len(dates)
    grid = SynthGrid()
    sites, inputs = root / "sites", root / "synthetic_inputs"
    sites.mkdir(parents=True)
    granules = []
    for i, (date, level) in enumerate(zip(dates, levels, strict=True), start=1):
        extra = {"grid": grid, **(common or {}), **(files or {}).get(date, {})}
        path = write_synthetic_gcov(inputs / f"synthetic_{date}.h5", date, convention=convention,
                                    level_db=level, seed=i, index=i, **extra)
        granules.append({"name": synthetic_name(date, i), "date": date, "start": f"{date}T06:00:00Z",
                         "release": "sample", "collection": "SYNTHETIC-TEST", "version": "T00000",
                         "counter": 1, "pols": list(extra.get("pols", ("HH",))), "bandwidth_mhz": 20.0,
                         "full_frame": True, "url": str(path), "browse": [], "size_bytes": path.stat().st_size})
    bbox = [round(v, 5) for v in grid.lonlat_bounds(margin_px=60)]
    config = {
        "id": SITE_ID, "title": "SYNTHETIC test site", "summary": "Synthetic data for automated tests only.",
        "is_sample": True, "notice": "SYNTHETIC test data, not an observation.",
        "citation": "Synthetic test data generated by pipeline/tests/synth.py.",
        "bbox": bbox, "product": "GCOV", "frequency": "A", "stack": "030_A_019", "releases": ["sample"],
        "polarizations": ["HH"], "access": "public", "working_resolution_m": 40,
        "backscatter": {"encoding": {"lo": -35, "hi": 5}, "display": {"min": -25, "max": 0, "ramp": "BrewerGreys9"}},
        "change": {"encoding": {"lo": -10, "hi": 10}, "display": {"min": -6, "max": 6, "ramp": "BrewerPuOr11"}},
        **(site or {}),
    }
    (sites / f"{SITE_ID}.yaml").write_text(yaml.safe_dump(config, sort_keys=False), encoding="utf-8")
    listing = {"site": SITE_ID, "generated_at": "2026-11-14T00:00:00Z", "product": "GCOV", "stack": "030_A_019",
               "direction": "ascending", "query": {"bbox": bbox, "releases": ["sample"]}, "granules": granules,
               "missing_passes": [{"date": "2026-06-13", "reason": "SYNTHETIC gap for tests"}], "excluded": []}
    (sites / f"{SITE_ID}.granules.json").write_text(json.dumps(listing, indent=2), encoding="utf-8")
    return Layout(sites_dir=sites, work_dir=root / "work", data_dir=root / "data")


@pytest.fixture(scope="session")
def synthetic_run(tmp_path_factory) -> SyntheticRun:
    root = tmp_path_factory.mktemp("e2e")
    layout = make_synthetic_site(root)
    code = run_site(load_site(SITE_ID, layout.sites_dir), layout)
    return SyntheticRun(layout=layout, grid=SynthGrid(), spot=BrightSpot(), exit_code=code)
